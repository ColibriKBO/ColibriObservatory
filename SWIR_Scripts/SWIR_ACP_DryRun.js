//
// SWIR_ACP_DryRun.js
//
// DRY-RUN ONLY.
// Reads a SWIR plate-solve result JSON and calculates the next
// telescope command. THIS SCRIPT DOES NOT MOVE THE TELESCOPE.
//
// First test assumes the previous commanded position was the
// original target stored in the JSON file.
//
// Later, the full closed-loop version will retain the actual
// previous commanded RA/Dec between iterations.

var RESULT_FILE = "D:\\SWIR_Pointing\\results\\pointing_001.json";

// Pointing thresholds
var SUCCESS_TOLERANCE_ARCSEC = 15.0;

// Refuse to even propose an automatic correction larger than 0.5 deg.
// This is just a safety limit for now.
var MAX_CORRECTION_ARCSEC = 1800.0;


// ---------------------------------------------------------------------
// Logging
// ---------------------------------------------------------------------

function log(msg)
{
    Util.Console.PrintLine(msg);
}


// ---------------------------------------------------------------------
// Read file
// ---------------------------------------------------------------------

function readTextFile(path)
{
    var fso = new ActiveXObject("Scripting.FileSystemObject");

    if (!fso.FileExists(path))
        throw new Error("Result file does not exist: " + path);

    var f = fso.OpenTextFile(path, 1, false);
    var txt = f.ReadAll();
    f.Close();

    return txt;
}


// ---------------------------------------------------------------------
// Parse JSON
//
// Using eval() here because ACP's Windows JScript engine may not
// provide JSON.parse(). This file is locally generated by our own
// solver, not arbitrary external input.
// ---------------------------------------------------------------------

function parseJson(text)
{
    return eval("(" + text + ")");
}


// ---------------------------------------------------------------------
// Numeric helpers
// ---------------------------------------------------------------------

function wrapHours(hours)
{
    while (hours < 0.0)
        hours += 24.0;

    while (hours >= 24.0)
        hours -= 24.0;

    return hours;
}


function formatRA(hours)
{
    hours = wrapHours(hours);

    var totalMs = Math.round(hours * 3600.0 * 1000.0);

    var h = Math.floor(totalMs / 3600000);
    totalMs -= h * 3600000;

    var m = Math.floor(totalMs / 60000);
    totalMs -= m * 60000;

    var s = totalMs / 1000.0;

    var hh = (h < 10 ? "0" : "") + h;
    var mm = (m < 10 ? "0" : "") + m;

    var ss = s.toFixed(3);
    if (s < 10.0)
        ss = "0" + ss;

    return hh + ":" + mm + ":" + ss;
}


function formatDec(deg)
{
    var sign = deg < 0.0 ? "-" : "+";
    var x = Math.abs(deg);

    var totalMs = Math.round(x * 3600.0 * 1000.0);

    var d = Math.floor(totalMs / 3600000);
    totalMs -= d * 3600000;

    var m = Math.floor(totalMs / 60000);
    totalMs -= m * 60000;

    var s = totalMs / 1000.0;

    var dd = (d < 10 ? "0" : "") + d;
    var mm = (m < 10 ? "0" : "") + m;

    var ss = s.toFixed(3);
    if (s < 10.0)
        ss = "0" + ss;

    return sign + dd + ":" + mm + ":" + ss;
}


// ---------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------

function main()
{
    log("============================================================");
    log("SWIR ACP POINTING CORRECTION - DRY RUN");
    log("============================================================");
    log("");
    log("Reading:");
    log(RESULT_FILE);
    log("");

    var text = readTextFile(RESULT_FILE);
    var result = parseJson(text);

    // -------------------------------------------------------------
    // Basic validation
    // -------------------------------------------------------------

    if (result.solved !== true)
        throw new Error("SWIR result does not contain a valid solution.");

    if (!isFinite(result.target_ra_deg) ||
        !isFinite(result.target_dec_deg) ||
        !isFinite(result.dra_coord_deg) ||
        !isFinite(result.ddec_deg) ||
        !isFinite(result.total_error_arcsec))
    {
        throw new Error("SWIR result contains invalid numeric values.");
    }

    if (result.total_error_arcsec > MAX_CORRECTION_ARCSEC)
    {
        throw new Error(
            "Correction rejected: " +
            result.total_error_arcsec.toFixed(2) +
            " arcsec exceeds safety limit of " +
            MAX_CORRECTION_ARCSEC.toFixed(1) +
            " arcsec."
        );
    }

    // -------------------------------------------------------------
    // FIRST-ITERATION TEST:
    //
    // The nominal target stored in the JSON was also the position
    // previously commanded to ACP.
    //
    // RA coordinate values are in degrees here.
    // -------------------------------------------------------------

    var previousRaDeg  = Number(result.target_ra_deg);
    var previousDecDeg = Number(result.target_dec_deg);

    var previousRaHours = previousRaDeg / 15.0;

    // -------------------------------------------------------------
    // Apply coordinate-space corrections
    //
    // IMPORTANT:
    // dra_coord_deg is used here, NOT dra_sky_arcsec.
    // -------------------------------------------------------------

    var correctedRaDeg =
        previousRaDeg + Number(result.dra_coord_deg);

    var correctedDecDeg =
        previousDecDeg + Number(result.ddec_deg);

    if (correctedDecDeg < -90.0 || correctedDecDeg > 90.0)
        throw new Error("Calculated declination is outside valid range.");

    var correctedRaHours = wrapHours(correctedRaDeg / 15.0);

    // Useful display values
    var raTimeCorrectionSec =
        Number(result.dra_coord_deg) * 240.0;

    var decCorrectionArcsec =
        Number(result.ddec_deg) * 3600.0;


    log("Plate solve: SUCCESS");
    log("");
    log("Solved image center:");
    log("  RA  = " + Number(result.center_ra_deg).toFixed(8) + " deg");
    log("  Dec = " + Number(result.center_dec_deg).toFixed(8) + " deg");
    log("");

    log("Measured pointing error:");
    log(
        "  RA sky = " +
        Number(result.dra_sky_arcsec).toFixed(2) +
        " arcsec"
    );
    log(
        "  Dec    = " +
        Number(result.ddec_arcsec).toFixed(2) +
        " arcsec"
    );
    log(
        "  Total  = " +
        Number(result.total_error_arcsec).toFixed(2) +
        " arcsec"
    );
    log("");

    log("Previous commanded position:");
    log("  RA  = " + formatRA(previousRaHours));
    log("  Dec = " + formatDec(previousDecDeg));
    log("");

    if (result.total_error_arcsec <= SUCCESS_TOLERANCE_ARCSEC)
    {
        log(
            "POINTING ALREADY WITHIN " +
            SUCCESS_TOLERANCE_ARCSEC.toFixed(1) +
            " ARCSEC TOLERANCE."
        );
        log("");
        log("No correction would be requested.");
        log("");
        log("DRY RUN ONLY - TELESCOPE WAS NOT MOVED.");
        log("============================================================");
        return;
    }

    log("Coordinate correction to apply:");
    log(
        "  RA  = " +
        (raTimeCorrectionSec >= 0 ? "+" : "") +
        raTimeCorrectionSec.toFixed(3) +
        " seconds of RA time"
    );
    log(
        "  Dec = " +
        (decCorrectionArcsec >= 0 ? "+" : "") +
        decCorrectionArcsec.toFixed(3) +
        " arcsec"
    );
    log("");

    log("PROPOSED NEXT ACP COMMAND:");
    log("  RA  = " + formatRA(correctedRaHours));
    log("  Dec = " + formatDec(correctedDecDeg));
    log("");

    log("DRY RUN ONLY - TELESCOPE WAS NOT MOVED.");
    log("============================================================");
}